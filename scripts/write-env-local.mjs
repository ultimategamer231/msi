// Writes .env.local from the running local Supabase stack (`pnpm env:local`). Local development only.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const status = JSON.parse(
  execFileSync("pnpm", ["-s", "supabase", "status", "-o", "json"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  }),
);
for (const key of ["API_URL", "ANON_KEY", "SERVICE_ROLE_KEY"]) {
  if (!status[key])
    throw new Error(`Local Supabase did not report ${key}. Is it running? Try \`pnpm db:start\`.`);
}
writeFileSync(
  ".env.local",
  [
    "# Generated by `pnpm env:local` from the local Supabase stack. Do not commit.",
    `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${status.ANON_KEY}`,
    `SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}`,
    "",
  ].join("\n"),
  { mode: 0o600 },
);
console.log("Wrote .env.local");
